// Command genapi generates the Telegram Bot API bindings of package
// telegram, the Update shortcuts of package gogram and the default answers
// of package sandbox from internal/apispec/api.html, a snapshot of the Bot
// API reference at https://core.telegram.org/bots/api. See package apispec.
//
// Run it through the Makefile or go generate from the repository root:
//
//	make generate
//	go generate ./...
//
// It refuses to run when api.html doesn't match api.lock. To move to a
// newer Bot API version, run make update-api. The generator fails loudly
// when a new spec needs a naming or typing decision it can't make on its
// own; add it to the tables in rules.go.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"

	"github.com/irisked/gogram/internal/apispec"
)

// The spec model, as parsed from the Bot API reference.
type (
	spec      = apispec.Spec
	apiMethod = apispec.Method
	apiType   = apispec.Type
	apiField  = apispec.Field
)

// readSpec parses a snapshot of the Bot API reference.
func readSpec(path string) (*spec, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	return apispec.Parse(b)
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("genapi: ")
	specPath := flag.String("spec", "internal/apispec/api.html", "snapshot of the Bot API reference; api.lock must be next to it")
	telegramDir := flag.String("telegram", ".", "directory of package telegram")
	gogramDir := flag.String("gogram", "..", "directory of package gogram")
	flag.Parse()

	lock, err := apispec.ReadLock(filepath.Join(filepath.Dir(*specPath), "api.lock"))
	if err != nil {
		log.Fatal(err)
	}
	raw, err := os.ReadFile(*specPath)
	if err != nil {
		log.Fatal(err)
	}
	if err := lock.Verify(raw); err != nil {
		log.Fatal(err)
	}
	s, err := apispec.Parse(raw)
	if err != nil {
		log.Fatal(err)
	}

	g := newGenerator(s)
	if err := g.analyze(); err != nil {
		log.Fatal(err)
	}

	// In order: the shortcut tests need the shortcuts written first.
	files := []struct {
		path  string
		write func(*bytes.Buffer)
	}{
		{filepath.Join(*telegramDir, "types_gen.go"), g.writeTypes},
		{filepath.Join(*telegramDir, "unions_gen.go"), g.writeUnions},
		{filepath.Join(*telegramDir, "methods_gen.go"), g.writeMethods},
		{filepath.Join(*telegramDir, "options_gen.go"), g.writeOptions},
		{filepath.Join(*telegramDir, "methods_gen_test.go"), g.writeMethodTests},
		{filepath.Join(*gogramDir, "update_gen.go"), g.writeShortcuts},
		{filepath.Join(*gogramDir, "update_gen_test.go"), g.writeShortcutTests},
		{filepath.Join(*gogramDir, "sandbox", "results_gen.go"), g.writeDefaultResults},
		{filepath.Join(*gogramDir, "sandbox", "server_gen_test.go"), g.writeSandboxTests},
	}
	for _, f := range files {
		path, write := f.path, f.write
		var buf bytes.Buffer
		fmt.Fprintf(&buf, "// Code generated by genapi from %s (%s) at %s. DO NOT EDIT.\n\n", s.Version, s.ReleaseDate, lock.URL)
		write(&buf)
		src, err := format.Source(buf.Bytes())
		if err != nil {
			os.WriteFile(path, buf.Bytes(), 0o644) // keep the broken output for debugging
			log.Fatalf("format %s: %v", path, err)
		}
		if err := os.WriteFile(path, src, 0o644); err != nil {
			log.Fatal(err)
		}
	}
	if err := errors.Join(g.errs...); err != nil {
		log.Fatal(err)
	}
}
